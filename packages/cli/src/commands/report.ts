import type { Command } from 'commander';
import { readFile } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import {
  writeReports,
  renderContractReport,
  renderPerformanceReport,
  renderSecurityReport,
  renderTestReport,
  ConfigError,
  type AnyReport,
  type ReportFormat,
} from '@apiforge/engine';
import { EXIT_CHECKS_FAILED, EXIT_SUCCESS } from '../exit-codes.js';
import { createUiFromCommand } from '../lib/context.js';
import { parseFormats } from '../lib/output.js';

interface ReportCommandOptions {
  format?: string;
  out?: string;
  json?: boolean;
  color?: boolean;
  quiet?: boolean;
  verbose?: boolean;
}

const VALID_KINDS = new Set(['test', 'performance', 'security', 'contract']);

function renderTerminal(report: AnyReport, color: boolean, verbose: boolean): string {
  switch (report.kind) {
    case 'test':
      return renderTestReport(report, { color, verbose });
    case 'performance':
      return renderPerformanceReport(report, { color });
    case 'security':
      return renderSecurityReport(report, { color, verbose });
    case 'contract':
      return renderContractReport(report, { color, verbose });
  }
}

/** `apiforge report` re-renders a previously saved JSON report. */
export function registerReportCommand(program: Command): void {
  program
    .command('report <file>')
    .description('Re-render a saved JSON report as HTML, JUnit XML, JSON or terminal output')
    .option(
      '-f, --format <formats>',
      'output formats, comma separated: terminal,json,html,junit',
      'html',
    )
    .option('-o, --out <dir>', 'directory for generated files (default: reports/)')
    .option('--json', 'print the report JSON to stdout')
    .option('-v, --verbose', 'show extra detail')
    .option('-q, --quiet', 'only print the final result')
    .option('--no-color', 'disable coloured output')
    .action(async (file: string, options: ReportCommandOptions) => {
      const ui = createUiFromCommand(options);
      const path = resolve(file);

      let document: unknown;
      try {
        document = JSON.parse(await readFile(path, 'utf8')) as unknown;
      } catch (error) {
        const code = (error as { code?: string }).code;
        if (code === 'ENOENT') throw new ConfigError(`Report file not found: ${file}`);
        throw new ConfigError(`Report file is not valid JSON: ${file}`, [
          String((error as Error).message),
        ]);
      }

      const report = document as AnyReport;
      if (
        !report ||
        typeof report !== 'object' ||
        !VALID_KINDS.has(String((report as { kind?: string }).kind))
      ) {
        throw new ConfigError(`Not an APIFORGE report: ${file}`, [
          'Expected a JSON report generated by `apiforge test|performance|security|contract`.',
        ]);
      }

      if (options.json) {
        process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
        process.exitCode =
          (report as { passed?: boolean }).passed === false ? EXIT_CHECKS_FAILED : EXIT_SUCCESS;
        return;
      }

      const formats: ReportFormat[] = parseFormats(options.format ? [options.format] : undefined, [
        'html',
      ]);
      if (formats.includes('terminal')) {
        ui.block(renderTerminal(report, ui.palette.enabled, options.verbose === true));
      }

      const fileFormats = formats.filter((format) => format !== 'terminal');
      if (fileFormats.length > 0) {
        const outDir = resolve(options.out ?? 'reports');
        const artifacts = await writeReports(report, {
          outDir,
          formats: fileFormats,
          baseName: `${basename(path, '.json')}-rerender`,
          writeLatest: true,
        });
        ui.success(`Rendered ${artifacts.length} artifact(s) from ${file}`);
        for (const artifact of artifacts) ui.detail(`${artifact.format}: ${artifact.path}`);
        ui.info(`Reports written to ${outDir}`);
      }

      process.exitCode =
        (report as { passed?: boolean }).passed === false ? EXIT_CHECKS_FAILED : EXIT_SUCCESS;
    });
}
